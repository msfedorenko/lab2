#include <iostream>
//Завдання 3 - 29
#include <cmath> // Підключення бібліотеки математичних функцій

using namespace std;

int main() {
    // Встановлення локалі для коректного виведення українського тексту
    setlocale(LC_ALL, "Ukrainian");

    // Виведення назви завдання у консоль
    cout << "=== Завдання 3 (Варіант 29) ===" << endl;
    cout << "Обчислення математичного виразу з дійсними змінними." << endl;

    // Визначення числа π як константи дійсного типу (згідно з вимогами методички)
    const double pi = 3.141592653589793;
    
    double x, numerator, denominator, y; // Дійсні змінні

    // 1) Виведення запрошення до вводу
    cout << endl << "Введіть дійсний аргумент x (x != 0): ";
    
    // 2) Введення змінної x
    cin >> x;

    // Перевірка ОДЗ (x не може дорівнювати 0 через логарифм та можливе ділення на нуль)
    if (x == 0) {
        cout << "Помилка: аргумент x не може дорівнювати 0 (делення на нуль у логарифмі)!" << endl;
        return 1;
    }

    // 3) Обчислення складників виразу (Варіант 29)
    // Обчислення log_5(|x|) через формулу переходу до натурального логарифма: ln(|x|) / ln(5)
    double log5_abs_x = log(fabs(x)) / log(5.0);

    // Проміжні обчислення для чисельника
    double x3 = pow(x, 3);
    double sin_sq = pow(sin(x3), 2); // sin^2(x^3)
    double cube_subexpr = fabs((x3 / 4.0) - sin_sq * 2.0) * log5_abs_x;

    // Чисельник: кубічний корінь з виразу (використовуємо функцію cbrt)
    numerator = cbrt(cube_subexpr);

    // Проміжні обчислення для знаменника (tg(x) у C++ реалізується через tan(x))
    double tan_x = tan(x);
    double sqrt_subexpr = fabs(3.0 * x + 2.5 * tan_x);

    // Перевірка знаменника на нуль
    denominator = pow(2.0, x) * sqrt(sqrt_subexpr);
    
    if (denominator == 0) {
        cout << "Помилка: знаменник дорівнює нулю!" << endl;
        return 1;
    }

    // Загальний результат функції
    y = numerator / denominator;

    // 4) Виведення результату з поясненнями
    cout << "\n--- Результати обчислень ---" << endl;
    cout << "Використана константа пі (π) = " << pi << endl;
    cout << "Значення функції y = " << y << endl;

    return 0;
}