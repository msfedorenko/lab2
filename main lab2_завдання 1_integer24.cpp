using namespace std;
int main() {
    // Встановлення локалі для коректного виведення українського тексту
    setlocale(LC_ALL, "Ukrainian");
    // Виведення назви завдання у консоль
    cout << "=== Завдання Integer24 ===" << endl;
    cout << "Визначення номера дня тижня для K-го дня року." << endl;
    int K, weekDay; // Декларація цілих змінних
    // 1) Виведення запрошення до вводу
    cout << endl << "Введіть день року K (від 1 до 365): ";
    // 2) Введення змінної K
    cin >> K;
    // Перевірка обмеження
    if (K < 1 || K > 365) {
        cout << "Помилка: число повинно бути в діапазоні від 1 до 365!" << endl;
        return 1;
    }
    // 3) Обчислення номера дня тижня (0 - неділя, 1 - понеділок, ..., 6 - субота)
    weekDay = K % 7;
    // 4) Виведення результату з поясненнями
    cout << "Для " << K << "-го дня року номер дня тижня дорівнює: " << weekDay << endl;
    return 0;
}
